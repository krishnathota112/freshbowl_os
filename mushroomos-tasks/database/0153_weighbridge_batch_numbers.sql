-- 0153 · WEIGHBRIDGE — batch numbers typed by Admin (weighment happens BEFORE the batch exists in Tasks) + the
-- owner's Excel layout: "req fresh weight 20000 · slip1 4000 → 16000 · … · slip5 5000 → -1000 reduce the weight".
--
-- Owner, 28 Sep 2026: "weighment is a thing which will be done before the batch creation so, add an input option
-- where they can enter batch numbers in the system." So a requirement no longer needs a Tasks batch:
--   wb_batch        the batch numbers as Admin types them ("182, 183, 184"), a note, one calculation slip, open/closed
--   wb_requirement  now hangs off wb_batch (wb_batch_id); the old tk_batch link (batch_id) stays, optional and unused
--   wb_v_slip       gains slip_no (1, 2, 3 … counting only valid slips) and balance_after_kg — the Excel's third column
-- Every rule from 0151 is unchanged: subtract net, over → alert at once, finished short → alert, void with reason.
-- Needs 0151. Checked before writing: wb_requirement / wb_slip / wb_alert were EMPTY on the live database (28 Sep).
-- Rollback: rollback_0153_weighbridge_batch_numbers.sql.

-- ── the batch numbers ───────────────────────────────────────────────────────────────────────────────────────────
create table if not exists public.wb_batch (
  id             uuid primary key default gen_random_uuid(),
  batch_no       text not null check (length(trim(batch_no)) > 0),
  note           text,
  calc_slip_path text,
  status         text not null default 'active' check (status in ('active', 'closed')),
  created_by     uuid references public.profiles(id),
  created_at     timestamptz not null default now(),
  closed_at      timestamptz,
  closed_by      uuid references public.profiles(id),
  close_note     text
);
-- the same numbers cannot be open twice ("182, 183" and "182,  183" count as the same)
create unique index if not exists wb_batch_no_open on public.wb_batch (lower(regexp_replace(batch_no, '\s+', '', 'g'))) where status = 'active';

alter table public.wb_batch enable row level security;
drop policy if exists wb_batch_read on public.wb_batch;
create policy wb_batch_read on public.wb_batch for select to authenticated
  using (public.has_role(variadic array['admin', 'gm', 'manager', 'weighbridge']::app_role[]));
revoke all on public.wb_batch from anon, authenticated;
grant select on public.wb_batch to authenticated;

-- ── requirements now belong to batch numbers ────────────────────────────────────────────────────────────────────
alter table public.wb_requirement add column if not exists wb_batch_id uuid references public.wb_batch(id);
-- any requirement made under 0151 (none on 28 Sep) gets batch numbers from its Tasks batch name
insert into public.wb_batch (batch_no, created_by, created_at)
select distinct b.name, r.created_by, r.created_at from public.wb_requirement r join public.tk_batch b on b.id = r.batch_id
 where r.wb_batch_id is null
   and not exists (select 1 from public.wb_batch w where lower(regexp_replace(w.batch_no, '\s+', '', 'g')) = lower(regexp_replace(b.name, '\s+', '', 'g')) and w.status = 'active');
update public.wb_requirement r set wb_batch_id = w.id
  from public.tk_batch b, public.wb_batch w
 where r.wb_batch_id is null and b.id = r.batch_id and w.status = 'active'
   and lower(regexp_replace(w.batch_no, '\s+', '', 'g')) = lower(regexp_replace(b.name, '\s+', '', 'g'));
alter table public.wb_requirement alter column wb_batch_id set not null;
alter table public.wb_requirement alter column batch_id drop not null;
alter table public.wb_requirement drop constraint if exists wb_requirement_batch_id_material_code_key;
alter table public.wb_requirement drop constraint if exists wb_requirement_batch_material;
alter table public.wb_requirement add constraint wb_requirement_batch_material unique (wb_batch_id, material_code);

-- slips keep the order they were entered in (two slips can share a timestamp)
alter table public.wb_slip add column if not exists entry_seq bigint generated by default as identity;

-- ── helpers now read the batch numbers ──────────────────────────────────────────────────────────────────────────
create or replace function public.wb_req_for_update(p_req uuid) returns public.wb_requirement
language plpgsql security definer set search_path = public as $fn$
declare r wb_requirement; st text;
begin
  select * into r from wb_requirement where id = p_req for update;
  if not found then raise exception 'No such requirement.'; end if;
  select status into st from wb_batch where id = r.wb_batch_id;
  if st <> 'active' then raise exception 'These batch numbers are closed. Admin can reopen them.'; end if;
  return r;
end $fn$;
revoke all on function public.wb_req_for_update(uuid) from public, anon, authenticated;

create or replace function public.wb_label(p_req uuid) returns text
language sql stable security definer set search_path = public as $fn$
  select 'Batch ' || b.batch_no || ' · ' || m.name
    from wb_requirement r join wb_batch b on b.id = r.wb_batch_id join wb_material m on m.code = r.material_code
   where r.id = p_req
$fn$;
revoke all on function public.wb_label(uuid) from public, anon, authenticated;

create or replace function public.wb_check_over(p_req uuid, p_slip uuid) returns boolean
language plpgsql security definer set search_path = public as $fn$
declare r wb_requirement; got numeric; v_over numeric;
begin
  select * into r from wb_requirement where id = p_req;
  got := public.wb_received_kg(p_req);
  v_over := got - r.required_kg;
  if v_over > r.tolerance_kg then
    insert into wb_alert (requirement_id, slip_id, kind, amount_kg, message)
    values (p_req, p_slip, 'over', v_over,
            public.wb_label(p_req) || ': received ' || public.wb_fmt(got) || ' against ' || public.wb_fmt(r.required_kg)
            || ' — over by ' || public.wb_fmt(v_over) || '. Reduce the weight.');
    return true;
  end if;
  return false;
end $fn$;
revoke all on function public.wb_check_over(uuid, uuid) from public, anon, authenticated;

create or replace function public.wb_finish(p_req uuid, p_note text default null) returns jsonb
language plpgsql security definer set search_path = public as $fn$
declare r wb_requirement; got numeric; v_short numeric;
begin
  perform public.assert_role(array['weighbridge', 'admin']::app_role[], 'finish a material');
  r := public.wb_req_for_update(p_req);
  if r.finished_at is not null then raise exception 'Already finished.'; end if;
  got := public.wb_received_kg(p_req);
  update wb_requirement set finished_at = now(), finished_by = auth.uid(), finish_note = nullif(trim(coalesce(p_note, '')), '') where id = p_req;
  v_short := r.required_kg - got;
  if v_short > r.tolerance_kg then
    insert into wb_alert (requirement_id, kind, amount_kg, message)
    values (p_req, 'short', v_short, public.wb_label(p_req) || ': finished at ' || public.wb_fmt(got) || ' against '
            || public.wb_fmt(r.required_kg) || ' — ' || public.wb_fmt(v_short) || ' SHORT.');
  end if;
  perform public.wb_log('wb_finish', 'wb_requirement', p_req, jsonb_build_object('received_kg', got, 'required_kg', r.required_kg));
  return jsonb_build_object('received_kg', got, 'required_kg', r.required_kg, 'short', v_short > r.tolerance_kg);
end $fn$;

-- ── Admin: batch numbers + the requirement sheet in one go ──────────────────────────────────────────────────────
-- p_rows: [{"material": "bagasse", "required_kg": 20000, "tolerance_kg": 0, "note": "…"}, …]
create or replace function public.wb_batch_create(p_batch_no text, p_note text, p_rows jsonb) returns uuid
language plpgsql security definer set search_path = public as $fn$
declare v uuid; x jsonb; n int := 0; no text; req uuid;
begin
  perform public.assert_role(array['admin']::app_role[], 'set weighment requirements');
  no := regexp_replace(trim(coalesce(p_batch_no, '')), '\s+', ' ', 'g');
  if no = '' then raise exception 'Enter the batch number(s).'; end if;
  if exists (select 1 from wb_batch where status = 'active' and lower(regexp_replace(batch_no, '\s+', '', 'g')) = lower(regexp_replace(no, '\s+', '', 'g'))) then
    raise exception 'Batch % is already open — add the material to it instead.', no;
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
    raise exception 'Add at least one material with its required weight.';
  end if;
  insert into wb_batch (batch_no, note, created_by) values (no, nullif(trim(coalesce(p_note, '')), ''), auth.uid()) returning id into v;
  for x in select * from jsonb_array_elements(p_rows) loop
    n := n + 1;
    begin
      req := public.wb_requirement_add(v, x->>'material', (x->>'required_kg')::numeric, coalesce((x->>'tolerance_kg')::numeric, 0), x->>'note');
    exception when invalid_text_representation then
      raise exception 'Row %: the weight must be a number.', n;
    end;
  end loop;
  perform public.wb_log('wb_batch_create', 'wb_batch', v, jsonb_build_object('batch_no', no, 'rows', p_rows));
  return v;
end $fn$;

create or replace function public.wb_requirement_add(p_batch uuid, p_material text, p_required_kg numeric,
  p_tolerance_kg numeric default 0, p_note text default null) returns uuid
language plpgsql security definer set search_path = public as $fn$
declare v uuid; st text; mname text;
begin
  perform public.assert_role(array['admin']::app_role[], 'set a weighment requirement');
  select status into st from wb_batch where id = p_batch;
  if st is distinct from 'active' then raise exception 'Choose open batch numbers.'; end if;
  select name into mname from wb_material where code = p_material and active;
  if mname is null then raise exception 'Choose a material.'; end if;
  if coalesce(p_required_kg, 0) <= 0 then raise exception '%: enter the required weight.', mname; end if;
  if coalesce(p_tolerance_kg, 0) < 0 then raise exception '%: the allowed difference cannot be negative.', mname; end if;
  if exists (select 1 from wb_requirement where wb_batch_id = p_batch and material_code = p_material) then
    raise exception '% is already on this batch — change its weight instead.', mname;
  end if;
  insert into wb_requirement (wb_batch_id, material_code, required_kg, tolerance_kg, note, created_by)
  values (p_batch, p_material, round(p_required_kg, 3), round(coalesce(p_tolerance_kg, 0), 3), nullif(trim(coalesce(p_note, '')), ''), auth.uid())
  returning id into v;
  perform public.wb_log('wb_requirement_add', 'wb_requirement', v,
    jsonb_build_object('batch', p_batch, 'material', p_material, 'required_kg', p_required_kg, 'tolerance_kg', p_tolerance_kg));
  return v;
end $fn$;

-- fix a typo in the numbers or the note
create or replace function public.wb_batch_update(p_batch uuid, p_batch_no text, p_note text) returns void
language plpgsql security definer set search_path = public as $fn$
declare b wb_batch; no text;
begin
  perform public.assert_role(array['admin']::app_role[], 'change batch numbers');
  select * into b from wb_batch where id = p_batch for update;
  if not found then raise exception 'No such batch.'; end if;
  no := regexp_replace(trim(coalesce(p_batch_no, '')), '\s+', ' ', 'g');
  if no = '' then raise exception 'Enter the batch number(s).'; end if;
  if b.status = 'active' and exists (select 1 from wb_batch where id <> p_batch and status = 'active'
       and lower(regexp_replace(batch_no, '\s+', '', 'g')) = lower(regexp_replace(no, '\s+', '', 'g'))) then
    raise exception 'Batch % is already open.', no;
  end if;
  update wb_batch set batch_no = no, note = nullif(trim(coalesce(p_note, '')), '') where id = p_batch;
  perform public.wb_log('wb_batch_update', 'wb_batch', p_batch, jsonb_build_object('batch_no', no, 'was', b.batch_no, 'note', p_note));
end $fn$;

-- one calculation slip for the batch: uploaded to weighments/<batch>/calc-..., then attached here
create or replace function public.wb_batch_set_calc_slip(p_batch uuid, p_path text) returns void
language plpgsql security definer set search_path = public as $fn$
declare st text;
begin
  perform public.assert_role(array['admin']::app_role[], 'attach a calculation slip');
  select status into st from wb_batch where id = p_batch for update;
  if st is distinct from 'active' then raise exception 'These batch numbers are closed.'; end if;
  if split_part(p_path, '/', 1) <> p_batch::text then raise exception 'The file is not filed under this batch.'; end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'weighments' and o.name = p_path and coalesce((o.metadata->>'size')::bigint, 0) > 0) then
    raise exception 'The file did not arrive. Upload it again.';
  end if;
  update wb_batch set calc_slip_path = p_path where id = p_batch;
  perform public.wb_log('wb_batch_set_calc_slip', 'wb_batch', p_batch, jsonb_build_object('path', p_path));
end $fn$;

-- Close: everything is weighed. Any material not yet finished is finished now (short → alert, as usual).
create or replace function public.wb_batch_close(p_batch uuid, p_note text default null) returns int
language plpgsql security definer set search_path = public as $fn$
declare st text; x record; n int := 0;
begin
  perform public.assert_role(array['admin']::app_role[], 'close batch numbers');
  select status into st from wb_batch where id = p_batch for update;
  if st is distinct from 'active' then raise exception 'Already closed.'; end if;
  for x in select id from wb_requirement where wb_batch_id = p_batch and finished_at is null loop
    perform public.wb_finish(x.id, coalesce(nullif(trim(coalesce(p_note, '')), ''), 'Batch closed'));
    n := n + 1;
  end loop;
  update wb_batch set status = 'closed', closed_at = now(), closed_by = auth.uid(), close_note = nullif(trim(coalesce(p_note, '')), '') where id = p_batch;
  perform public.wb_log('wb_batch_close', 'wb_batch', p_batch, jsonb_build_object('finished_now', n, 'note', p_note));
  return n;
end $fn$;

create or replace function public.wb_batch_reopen(p_batch uuid, p_reason text) returns void
language plpgsql security definer set search_path = public as $fn$
declare b wb_batch;
begin
  perform public.assert_role(array['admin']::app_role[], 'reopen batch numbers');
  select * into b from wb_batch where id = p_batch for update;
  if not found or b.status <> 'closed' then raise exception 'These batch numbers are not closed.'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Say why it is reopened.'; end if;
  if exists (select 1 from wb_batch where id <> p_batch and status = 'active'
       and lower(regexp_replace(batch_no, '\s+', '', 'g')) = lower(regexp_replace(b.batch_no, '\s+', '', 'g'))) then
    raise exception 'Batch % is open again as a new entry — use that one.', b.batch_no;
  end if;
  update wb_batch set status = 'active', closed_at = null, closed_by = null, close_note = null where id = p_batch;
  perform public.wb_log('wb_batch_reopen', 'wb_batch', p_batch, jsonb_build_object('reason', trim(p_reason)));
end $fn$;

