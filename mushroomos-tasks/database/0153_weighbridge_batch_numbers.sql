create view public.wb_v_requirement with (security_invoker = on) as
select r.id, r.wb_batch_id as batch_id, b.batch_no as batch_name, b.status as batch_status, r.material_code, m.name as material_name, m.sort,
       r.required_kg, r.tolerance_kg, r.note, coalesce(r.calc_slip_path, b.calc_slip_path) as calc_slip_path, r.finished_at, r.finish_note, r.created_at,
       g.received_kg, r.required_kg - g.received_kg as remaining_kg, g.slips,
       case when g.received_kg - r.required_kg > r.tolerance_kg then 'over'
            when r.required_kg - g.received_kg <= r.tolerance_kg then 'complete'
            when r.finished_at is not null then 'short'
            else 'receiving' end as state,
       (select count(*) from wb_alert a where a.requirement_id = r.id and a.ack_at is null)::int as open_alerts,
       b.note as batch_note, b.created_at as batch_created_at
  from wb_requirement r
  join wb_batch b on b.id = r.wb_batch_id
  join wb_material m on m.code = r.material_code
  cross join lateral (select coalesce(sum(s.net_kg), 0) as received_kg, count(*)::int as slips
                        from wb_slip s where s.requirement_id = r.id and s.voided_at is null) g
 where public.has_role(variadic array['admin', 'gm', 'manager', 'weighbridge']::app_role[]);

-- slip_no and balance_after_kg: the Excel sheet's "slip1 4000 → 16000" (voided slips get neither)
create view public.wb_v_slip with (security_invoker = on) as
select s.*, r.wb_batch_id as batch_id, b.batch_no as batch_name, r.material_code, m.name as material_name,
       p.display_name as recorded_by_name, pv.display_name as voided_by_name,
       case when s.voided_at is null then count(*) filter (where s.voided_at is null)
            over (partition by s.requirement_id order by s.recorded_at, s.entry_seq rows unbounded preceding) end::int as slip_no,
       case when s.voided_at is null then r.required_kg - sum(case when s.voided_at is null then s.net_kg else 0 end)
            over (partition by s.requirement_id order by s.recorded_at, s.entry_seq rows unbounded preceding) end as balance_after_kg,
       r.required_kg, r.tolerance_kg
  from wb_slip s
  join wb_requirement r on r.id = s.requirement_id
  join wb_batch b on b.id = r.wb_batch_id
  join wb_material m on m.code = r.material_code
  left join profiles p on p.id = s.recorded_by
  left join profiles pv on pv.id = s.voided_by
 where public.has_role(variadic array['admin', 'gm', 'manager', 'weighbridge']::app_role[]);

create view public.wb_v_alert with (security_invoker = on) as
select a.*, r.wb_batch_id as batch_id, b.batch_no as batch_name, m.name as material_name, s.ticket_no, pa.display_name as ack_by_name
  from wb_alert a
  join wb_requirement r on r.id = a.requirement_id
  join wb_batch b on b.id = r.wb_batch_id
  join wb_material m on m.code = r.material_code
  left join wb_slip s on s.id = a.slip_id
  left join profiles pa on pa.id = a.ack_by
 where public.has_role(variadic array['admin', 'gm', 'manager']::app_role[]);

-- batch numbers, open first (Admin's list)
create view public.wb_v_batch with (security_invoker = on) as
select b.id, b.batch_no, b.batch_no as name, b.note, b.calc_slip_path, b.status, b.created_at, b.closed_at, b.close_note,
       pc.display_name as created_by_name,
       (select count(*) from wb_requirement r where r.wb_batch_id = b.id)::int as materials,
       (select count(*) from wb_requirement r where r.wb_batch_id = b.id and r.finished_at is null)::int as unfinished
  from wb_batch b
  left join profiles pc on pc.id = b.created_by
 where public.has_role(variadic array['admin', 'gm', 'manager', 'weighbridge']::app_role[]);

revoke all on public.wb_v_requirement, public.wb_v_slip, public.wb_v_alert, public.wb_v_batch from anon;
grant select on public.wb_v_requirement, public.wb_v_slip, public.wb_v_alert, public.wb_v_batch to authenticated;
notify pgrst, 'reload schema';
