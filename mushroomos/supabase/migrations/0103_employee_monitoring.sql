-- employee monitoring tool where we monitor if the employees are doing the work or not").
--   1 · operator = supervisor: an operator account acts as a supervisor everywhere on the server.
--   2 · The before photo must be taken within the grace (30 min) of Start; later, a late ticket is needed.
--       Before, both photos could be taken back to back at the end of the task.
--   3 · v_person_activity: per person, today (factory time) — starts, finishes, work open now, late finishes,
--       before photos taken late, tickets raised / rejected, photos, last action. Admin / GM / manager only.
--   4 · v_override_log: every override and decision (onboarding, DEMO flag, time corrections, ticket decisions,
--       holds, returns, cancellations, deviation and Lab decisions, process changes). Admin / GM / manager only.
--   5 · The audit trail is no longer readable by supervisors (it is the record of their own work).
