create or replace view public.v_person_activity with (security_invoker = on) as
with tz as (select coalesce((select timezone from factory_clock limit 1), 'Asia/Kolkata') as z),
day as (select (date_trunc('day', now() at time zone tz.z)) at time zone tz.z as d0 from tz)
select p.id as person_id, p.display_name,
       case when p.role = 'operator' then 'supervisor'::app_role else p.role end as role,
       (select count(*) from batch_activity ba, day where ba.started_by = p.id and ba.actual_start >= day.d0) as started_today,
       (select count(*) from batch_activity ba, day where ba.submitted_by = p.id and ba.submitted_at >= day.d0) as finished_today,
       (select count(*) from batch_activity ba join master_batch mb on mb.id = ba.master_batch_id
         where ba.started_by = p.id and ba.state::text in ('IN_PROGRESS', 'RETURNED') and mb.status = 'active') as open_now,
       (select count(*) from batch_activity ba join master_batch mb on mb.id = ba.master_batch_id, day
         where ba.submitted_by = p.id and ba.submitted_at >= day.d0 and not mb.is_demo and not ba.is_hold
           and ba.planned_end_at is not null
           and ba.actual_end > ba.planned_end_at + make_interval(secs => (coalesce((select sum(er.approved_extension_hr) from extension_request er
                 where er.batch_activity_id = ba.id and public.extension_is_effective(er.status)), 0) * 3600)::int)
                 + make_interval(mins => coalesce((select x.late_grace_min from extension_policy x where x.id), 30))) as late_finishes_today,
       (select count(*) from evidence_media m join batch_activity ba on ba.id = m.batch_activity_id, day
         where m.uploaded_by = p.id and m.uploaded_at >= day.d0 and m.requirement_key = 'BEFORE_PHOTO'
           and ba.actual_start is not null and m.uploaded_at > ba.actual_start + interval '30 minutes') as late_before_photos_today,
       (select count(*) from extension_request er, day where er.requested_by = p.id and er.requested_at >= day.d0) as tickets_today,
       (select count(*) from extension_request er, day where er.requested_by = p.id and er.requested_at >= day.d0 and er.status = 'ADMIN_REJECTED') as tickets_rejected_today,
       (select count(*) from evidence_media m, day where m.uploaded_by = p.id and m.uploaded_at >= day.d0) as photos_today,
       (select max(a.occurred_at) from audit_event a where a.actor_id = p.id) as last_action_at,
       (select a.action from audit_event a where a.actor_id = p.id order by a.occurred_at desc limit 1) as last_action
  from profiles p
 where p.is_active
   and public.has_role(variadic array['gm', 'manager', 'admin']::app_role[]);
grant select on public.v_person_activity to authenticated;

create or replace view public.v_override_log with (security_invoker = on) as
select a.id, a.occurred_at, a.actor_id, pr.display_name as actor_name,
       case when a.actor_role::text = 'operator' then 'supervisor' else a.actor_role::text end as actor_role,
       a.action, a.entity_table, a.entity_id, a.reason, a.after_state,
       coalesce(mb.code, mb2.code) as batch_code, ba.title as activity_title, ba.scope_label
  from audit_event a
  left join profiles pr on pr.id = a.actor_id
  left join batch_activity ba on a.entity_table = 'batch_activity' and ba.id::text = a.entity_id
  left join master_batch mb on mb.id = ba.master_batch_id
  left join master_batch mb2 on a.entity_table = 'master_batch' and mb2.id::text = a.entity_id
 where a.action in ('onboard_batch', 'mark_batch_demo', 'correct_actual', 'admin_decide_extension', 'cancel_batch',
                    'hold_activity', 'release_activity', 'return_activity', 'skip_activity', 'accept_with_deviation',
                    'gm_decide_override', 'verify_corrective_action', 'decide_lab_submission', 'set_current_process',
                    'publish_process_definition', 'activate_batch', 'set_batch_start_at', 'assign_activity',
                    'request_extension', 'cancel_extension')
   and public.has_role(variadic array['gm', 'manager', 'admin']::app_role[]);
grant select on public.v_override_log to authenticated;

